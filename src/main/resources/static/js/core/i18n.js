let _currentLang = localStorage.getItem('slotlab-lang') || 'en';

function t(key) {
  return (_I18N[_currentLang] && _I18N[_currentLang][key]) || _I18N.en[key] || key;
}

function setLang(lang) {
  _currentLang = lang;
  localStorage.setItem('slotlab-lang', lang);
  applyI18n();
}

function applyI18n() {
  /* Update all data-i18n elements */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const attr = el.dataset.i18nAttr;
    if (attr) {
      el.setAttribute(attr, t(key));
    } else {
      el.textContent = t(key);
    }
  });

  /* Update all data-i18n-html elements (innerHTML — for rich tooltip content) */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  /* Update language button label */
  const langToggleBtn = document.getElementById('lang-toggle-btn');
  if (langToggleBtn) {
    const labels = { en: 'EN', ru: 'RU', zh: '中文' };
    langToggleBtn.textContent = labels[_currentLang] || 'EN';
  }
  document.querySelectorAll('#lang-dropdown .lang-opt').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === _currentLang);
  });

  /* Sync dynamic placeholder text on RTP inputs */
  const genReelsFirst = document.getElementById('rtp-chances-list');
  if (genReelsFirst) {
    const span = genReelsFirst.querySelector('span[style*="italic"]');
    if (span) span.textContent = t('rtp.generate_reels_first');
  }
  const mwList = document.getElementById('megaways-heights-list');
  if (mwList) {
    const span = mwList.querySelector('span[style*="italic"]');
    if (span) span.textContent = t('rtp.generate_reels_first');
  }

  /* Placeholders for spin test */
  const rtpIdxEl = document.getElementById('spin-test-reel-idx');
  if (rtpIdxEl) rtpIdxEl.placeholder = t('spin.reel_idx_placeholder');

  /* No-generations / no-simulations empty states */
  const historyEmpty = document.getElementById('history-empty');
  if (historyEmpty) historyEmpty.textContent = t('gen.no_generations');
  const rtpHistoryEmpty = document.getElementById('rtp-history-empty');
  if (rtpHistoryEmpty) rtpHistoryEmpty.textContent = t('rtp.no_simulations');

  /* Add payline button text */
  const addPaylineBtn = document.getElementById('add-payline-btn');
  if (addPaylineBtn) {
    const count = document.querySelectorAll('.rtp-line-row').length;
    addPaylineBtn.textContent = t('rtp.add_payline') + ' (' + count + ')';
  }

  /* Symbol table headers */
  const symHeaders = document.querySelectorAll('.rtp-sym-header span');
  if (symHeaders.length >= 3) {
    symHeaders[0].textContent = t('rtp.sym_id');
    symHeaders[1].textContent = t('rtp.sym_tile_type');
    symHeaders[2].textContent = t('rtp.sym_paytable');
  }

  /* Generate reel set names, restriction labels */
  document.querySelectorAll('.reel-set-name').forEach((el, i) => {
    el.textContent = t('gen.reel_set_label') + i;
  });
  document.querySelectorAll('.restriction-label').forEach((el, i) => {
    el.textContent = t('gen.restriction_label') + (i + 1);
  });

  /* Import modal */
  const importTitle = document.querySelector('#import-counts-modal .modal-title');
  if (importTitle) importTitle.textContent = t('gen.import_title');
  const importDesc = document.querySelector('#import-counts-modal .modal-body > div');
  if (importDesc && importDesc.tagName === 'DIV') importDesc.textContent = t('gen.import_paste');

  /* Confirm modal */
  const confirmTitle = document.getElementById('confirm-modal-title');
  if (confirmTitle) confirmTitle.textContent = t('modal.confirm');
  const confirmOk = document.getElementById('confirm-modal-ok');
  if (confirmOk) confirmOk.textContent = t('modal.delete');

  /* Rtp placeholder */
  const rtpPlaceholder = document.querySelector('.rtp-placeholder span:not([style])');
  if (rtpPlaceholder && rtpPlaceholder.textContent.match(/Configure|Настройте|配置符号/)) {
    rtpPlaceholder.textContent = t('rtp.configure_run');
  }
  const spinPlaceholder = document.querySelector('#spin-test-results-body .rtp-placeholder span');
  if (spinPlaceholder && spinPlaceholder.textContent.match(/Configure|Настройте|配置选项/)) {
    spinPlaceholder.textContent = t('spin.configure_run');
  }
}

/* Lang toggle button in header — inserted by app-init.js */
function _buildLangBtn() {
  const labels = { en: 'EN', ru: 'RU', zh: '中文' };

  const wrap = document.createElement('div');
  wrap.className = 'lang-switcher';

  const toggleBtn = document.createElement('button');
  toggleBtn.className = 'lang-toggle-btn';
  toggleBtn.id = 'lang-toggle-btn';
  toggleBtn.setAttribute('aria-label', t('header.lang'));
  toggleBtn.textContent = labels[_currentLang] || 'EN';

  const dropdown = document.createElement('div');
  dropdown.className = 'lang-dropdown';
  dropdown.id = 'lang-dropdown';

  ['en', 'ru', 'zh'].forEach(lang => {
    const opt = document.createElement('button');
    opt.className = 'lang-opt' + (lang === _currentLang ? ' active' : '');
    opt.dataset.lang = lang;
    opt.textContent = labels[lang];
    opt.addEventListener('click', e => {
      e.stopImmediatePropagation();
      dropdown.style.display = 'none';
      _dropdownOpen = false;
      setLang(lang);
    });
    dropdown.appendChild(opt);
  });

  let _dropdownOpen = false;

  toggleBtn.addEventListener('click', e => {
    e.stopImmediatePropagation();
    _dropdownOpen = !_dropdownOpen;
    dropdown.style.display = _dropdownOpen ? 'block' : 'none';
  });

  document.addEventListener('click', () => {
    if (_dropdownOpen) {
      _dropdownOpen = false;
      dropdown.style.display = 'none';
    }
  });

  wrap.appendChild(toggleBtn);
  wrap.appendChild(dropdown);
  return wrap;
}
